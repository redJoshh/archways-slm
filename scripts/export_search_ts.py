"""Write assistant-ts/src/searchData.ts: the data the on-phone search needs.

Usage: uv run python scripts/export_search_ts.py [--check]

From the Python reference (ADR 0006: the search runs on the phone):
- STOPWORDS: fakebackend.AND_V2_STOPWORDS (and_v3 uses the same)
- SYNONYMS: contracts/search_synonyms_v1.json via fakebackend.SYNONYMS
- PY_SPACE: every code point for which Python's str.isspace() is true,
  because the query is split with str.split() (no arguments)
- INLINE_TAGS, PLAIN_SPACE and ENTITIES: excerpt.py's plain-text rule
  (the HTML5 named references that end in ";", as html.entities.html5)
- the defaults and limits feedindex.py uses

Deterministic; --check exits 1 if the committed file differs. ASCII only.
"""

import argparse
import html.entities
import json
import sys
from pathlib import Path

from archways_assistant import excerpt, feedindex
from archways_assistant.fakebackend import (
    AND_V2_STOPWORDS,
    EXCERPT_CHARS,
    SYNONYMS,
)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assistant-ts" / "src" / "searchData.ts"
CONTRACT = ROOT / "contracts" / "search_announcements.schema.json"


def literal(value) -> str:
    return json.dumps(value, ensure_ascii=True)


def render() -> str:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    arguments = contract["$defs"]["arguments"]["properties"]
    py_space = [code for code in range(0x110000) if chr(code).isspace()]
    plain_space = sorted(map(ord, excerpt.WHITESPACE))
    entities = {
        name[:-1]: value
        for name, value in sorted(html.entities.html5.items())
        if name.endswith(";")
    }
    lines = [
        "// Generated by scripts/export_search_ts.py; do not edit.",
        "// Sources: src/archways_assistant/fakebackend.py, feedindex.py,",
        "// excerpt.py, contracts/search_synonyms_v1.json,",
        "// contracts/search_announcements.schema.json, Python html.entities.",
        "",
        'export const MATCHER = "and_v3";',
        f"export const DAYS_DEFAULT = {literal(arguments['days']['default'])};",
        f"export const LIMIT_DEFAULT = {literal(arguments['limit']['default'])};",
        f"export const EXCERPT_CHARS = {EXCERPT_CHARS};",
        f"export const TITLE_MAX_CHARS = {feedindex.TITLE_MAX_CHARS};",
        f"export const YEAR_MIN = {feedindex.YEAR_MIN};",
        f"export const YEAR_MAX = {feedindex.YEAR_MAX};",
        "export const STOPWORDS: readonly string[] = "
        + literal(sorted(AND_V2_STOPWORDS))
        + ";",
        "export const SYNONYMS: { readonly [word: string]: readonly string[] } = "
        + literal(dict(sorted(SYNONYMS.items())))
        + ";",
        "// Code points where Python's str.isspace() is true (query splitting).",
        "export const PY_SPACE: readonly number[] = ["
        + ", ".join(f"0x{c:04x}" for c in py_space)
        + "];",
        "export const PLAIN_SPACE: readonly number[] = ["
        + ", ".join(f"0x{c:04x}" for c in plain_space)
        + "];",
        "export const INLINE_TAGS: readonly string[] = "
        + literal(sorted(excerpt.INLINE_TAGS))
        + ";",
        '// HTML5 named references (name without the closing ";").',
        "export const ENTITIES: { readonly [name: string]: string } = {",
    ]
    for name, value in entities.items():
        lines.append(f"  {literal(name)}: {literal(value)},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if current != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date; rerun the script")
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.write_bytes(text.encode("ascii"))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text):,} bytes)")


if __name__ == "__main__":
    main()
