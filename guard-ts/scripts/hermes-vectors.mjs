// Run the guard vectors under the Hermes CLI (hermes-engine-cli, Hermes
// 0.12). A smoke test only: the Gate 1 app's Hermes is newer, and the
// phone run is the real Hermes check.
//
// Builds dist-hermes/run-vectors.js from the tsc output (exports and
// imports stripped, the vector file inlined, plain script, no modules),
// then runs it with the platform's hermes binary. Zero dependencies.
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const vectorsPath =
  process.env.GUARD_VECTORS ?? join(root, "..", "tests", "vectors", "guard_vectors.json");

function plainScript(file) {
  return readFileSync(join(root, "dist", "src", file), "utf8")
    .replace(/^import[^;]*;\s*$/gm, "")
    .replace(/^export \{[^}]*\};\s*$/gm, "")
    .replace(/^export /gm, "");
}

const runner = `
var report = runVectors(VECTORS);
var log = typeof print === "function" ? print : console.log;
log("hermes guard vectors: " + report.passed + "/" + report.total + " passed, " +
    report.failed + " failed; spec problems: " +
    (report.specProblems.length ? report.specProblems.join(", ") : "none"));
for (var i = 0; i < report.failures.length; i++) {
  log("FAIL " + JSON.stringify(report.failures[i]));
}
if (report.failed || report.specProblems.length) { throw new Error("vectors failed"); }
`;

const bundle = [
  "// Generated by scripts/hermes-vectors.mjs; do not edit.",
  plainScript("spec.js"),
  plainScript("guard.js"),
  plainScript("runVectors.js"),
  "var VECTORS = " + readFileSync(vectorsPath, "utf8").trim() + ";",
  runner,
].join("\n");
mkdirSync(join(root, "dist-hermes"), { recursive: true });
const out = join(root, "dist-hermes", "run-vectors.js");
writeFileSync(out, bundle);

const binaries = {
  win32: ["win64-bin", "hermes.exe"],
  darwin: ["osx-bin", "hermes"],
  linux: ["linux64-bin", "hermes"],
};
const parts = binaries[process.platform];
const hermes = parts && join(root, "node_modules", "hermes-engine-cli", ...parts);
if (!hermes || !existsSync(hermes)) {
  console.error(`No Hermes CLI binary for ${process.platform} (looked for ${hermes}).`);
  process.exit(2);
}
const run = spawnSync(hermes, [out], { encoding: "utf8" });
process.stdout.write(run.stdout ?? "");
process.stderr.write(run.stderr ?? "");
process.exit(run.status ?? 1);
