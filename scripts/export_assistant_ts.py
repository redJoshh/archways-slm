"""Write assistant-ts/src/generated.ts from the frozen prompts and the contract.

Usage: uv run python scripts/export_assistant_ts.py [--check]

The generated file holds the UAT prompt texts (query v1, answer v1) with
their SHA-256, the contract bounds the port checks, and the messages and
limits of archways_assistant.assistant. Never edit it by hand; rerun this
script. --check exits 1 if the committed file differs from what this
script would write (tests/test_assistant.py runs the same comparison).

All strings are written as ASCII-only JSON literals, which are valid
TypeScript and safe for Hermes.
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

from archways_assistant import assistant
from archways_assistant.e2escore import (
    FALLBACK_HEADER,
    LAST_RESORT_MESSAGE,
    NOT_FOUND_MESSAGE,
)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assistant-ts" / "src" / "generated.ts"
QUERY_PROMPT = ROOT / "prompts" / "e2e_query_v1.txt"
ANSWER_PROMPT = ROOT / "prompts" / "e2e_answer_v1.txt"
CONTRACT = ROOT / "contracts" / "search_announcements.schema.json"


def literal(value) -> str:
    return json.dumps(value, ensure_ascii=True)


def render() -> str:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    arguments = contract["$defs"]["arguments"]["properties"]
    announcement = contract["$defs"]["announcement"]
    result = contract["$defs"]["result"]
    if list(announcement["required"]) != list(assistant.KEYS):
        sys.exit("contract result keys differ from assistant.KEYS")
    if contract["$defs"]["arguments"]["required"] != ["query"]:
        sys.exit("contract required arguments changed")
    if arguments["query"].get("pattern") != "\\S":
        sys.exit("contract query pattern changed")

    prompts = {}
    for name, path in (("QUERY", QUERY_PROMPT), ("ANSWER", ANSWER_PROMPT)):
        data = path.read_bytes()
        prompts[name] = (data.decode("utf-8"), hashlib.sha256(data).hexdigest())

    constants = [
        ("QUERY_PROMPT_FILE", "prompts/e2e_query_v1.txt"),
        ("QUERY_PROMPT_TEXT", prompts["QUERY"][0]),
        ("QUERY_PROMPT_SHA256", prompts["QUERY"][1]),
        ("ANSWER_PROMPT_FILE", "prompts/e2e_answer_v1.txt"),
        ("ANSWER_PROMPT_TEXT", prompts["ANSWER"][0]),
        ("ANSWER_PROMPT_SHA256", prompts["ANSWER"][1]),
        ("NOT_FOUND_MESSAGE", NOT_FOUND_MESSAGE),
        ("LAST_RESORT_MESSAGE", LAST_RESORT_MESSAGE),
        ("FALLBACK_HEADER", FALLBACK_HEADER),
        ("BUDGET_CASE_TOKENS", assistant.BUDGET_CASE_TOKENS),
        ("QUESTION_MAX_CHARS", assistant.QUESTION_MAX_CHARS),
        ("BAR_MS", assistant.BAR_MS),
        ("ANSWER_LOAD_MS", assistant.ANSWER_LOAD_MS),
        ("OVERHEAD_MS", assistant.OVERHEAD_MS),
        ("GEN_TOKENS", assistant.GEN_TOKENS),
        ("CASE_TOKENS_CTX_MAX", assistant.CASE_TOKENS_CTX_MAX),
        ("RATE_MIN", assistant.RATE_MIN),
        ("RATE_MAX", assistant.RATE_MAX),
        ("PROMPT_N_MIN", assistant.PROMPT_N_MIN),
        ("PREDICTED_N_MIN", assistant.PREDICTED_N_MIN),
        ("QUERY_MIN_CHARS", arguments["query"]["minLength"]),
        ("QUERY_MAX_CHARS", arguments["query"]["maxLength"]),
        ("DAYS_MIN", arguments["days"]["minimum"]),
        ("DAYS_MAX", arguments["days"]["maximum"]),
        ("LIMIT_MIN", arguments["limit"]["minimum"]),
        ("LIMIT_MAX", arguments["limit"]["maximum"]),
        ("RESULTS_MAX", result["maxItems"]),
        ("TITLE_MAX_CHARS", announcement["properties"]["title"]["maxLength"]),
        ("EXCERPT_MAX_CHARS", announcement["properties"]["excerpt"]["maxLength"]),
    ]
    lines = [
        "// Generated by scripts/export_assistant_ts.py; do not edit.",
        "// Sources: prompts/e2e_query_v1.txt, prompts/e2e_answer_v1.txt,",
        "// contracts/search_announcements.schema.json,",
        "// src/archways_assistant/assistant.py and e2escore.py.",
        "",
    ]
    for name, value in constants:
        lines.append(f"export const {name} = {literal(value)};")
    keys = ", ".join(literal(key) for key in assistant.KEYS)
    lines.append(f"export const RESULT_KEYS: readonly string[] = [{keys}];")
    arguments_keys = ", ".join(literal(key) for key in arguments)
    lines.append(f"export const ARGUMENT_KEYS: readonly string[] = [{arguments_keys}];")
    spaces = ", ".join(
        f"0x{code:04x}" for code in sorted(map(ord, assistant.ECMA_WHITESPACE))
    )
    lines.append(f"export const ECMA_WHITESPACE: readonly number[] = [{spaces}];")
    weekdays = ", ".join(literal(day) for day in assistant.WEEKDAYS)
    lines.append(
        f"// Monday first, as Python's date.weekday().\n"
        f"export const WEEKDAYS: readonly string[] = [{weekdays}];"
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if current != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date; rerun the script")
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("ascii"))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
